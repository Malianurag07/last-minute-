const DAY = 24 * 60 * 60 * 1000;
const HOUR = 60 * 60 * 1000;

const ago = (ms: number) => new Date(Date.now() - ms).toISOString();
const fromNow = (ms: number) => new Date(Date.now() + ms).toISOString();

let rid = 0;
const r = (author: string, rating: number, text: string, daysAgo: number): Review => ({
  id: `rv${++rid}`,
  author,
  rating,
  text,
  date: ago(daysAgo * DAY),
});

type P = Omit<Provider, 'rating' | 'verified' | 'joinedAt' | 'available' | 'languages'> &
  Partial<Pick<Provider, 'verified' | 'available' | 'languages'>>;

const make = (p: P): Provider => {
  const rating = p.reviews.length
    ? Math.round((p.reviews.reduce((s, x) => s + x.rating, 0) / p.reviews.length) * 10) / 10
    : 0;
  return {
    verified: true,
    available: true,
    languages: ['Hindi', 'English'],
    joinedAt: ago(120 * DAY),
    ...p,
    rating,
  };
};

